import logging
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple
from app.config import settings
from app.schemas import CandidateTrack

logger = logging.getLogger("ytm")


class YouTubeMusicClient:
    def __init__(self) -> None:
        self.client = None
        self._playlist_cache: Dict[str, str] = {}
        self.init_client()

    def init_client(self) -> bool:
        auth_file = Path(settings.ytm_auth_file) if settings.ytm_auth_file else None
        if not auth_file or not auth_file.exists():
            logger.warning("YTM_AUTH_FILE not set or does not exist: %s", auth_file)
            self.client = None
            return False

        try:
            from ytmusicapi import YTMusic

            self.client = YTMusic(str(auth_file))
            logger.info("Successfully initialized ytmusicapi with %s", auth_file)
            return True
        except Exception as e:
            logger.error("Failed to initialize ytmusicapi: %s", e)
            self.client = None
            return False

    @property
    def is_authenticated(self) -> bool:
        return self.client is not None

    def get_or_create_playlist(self, name: str) -> str:
        if name in self._playlist_cache:
            return self._playlist_cache[name]

        if not self.client:
            raise RuntimeError("YouTube Music client is not authenticated")

        playlists = self.client.get_library_playlists(limit=100)
        for pl in playlists:
            if pl.get("title", "").strip().lower() == name.strip().lower():
                pl_id = pl["playlistId"]
                self._playlist_cache[name] = pl_id
                return pl_id

        # If not found, create it
        pl_id = self.client.create_playlist(
            title=name,
            description=f"Auto-generated by Ginininini for {name}",
            privacy_status="PRIVATE",
        )
        self._playlist_cache[name] = pl_id
        return pl_id

    def get_inbox_video_ids(self, playlist_id: str) -> Set[str]:
        if not self.client:
            return set()
        try:
            playlist_data = self.client.get_playlist(playlist_id, limit=500)
            tracks = playlist_data.get("tracks", [])
            return {t.get("videoId") for t in tracks if t.get("videoId")}
        except Exception as e:
            logger.warning("Error fetching tracks from playlist %s: %s", playlist_id, e)
            return set()

    def search_songs(self, query: str, limit: int = 4) -> List[Dict[str, Any]]:
        if not self.client:
            # Fall back to unauthenticated public search if client auth is not configured
            from ytmusicapi import YTMusic

            unauth = YTMusic()
            return unauth.search(query=query, filter="songs", limit=limit)
        return self.client.search(query=query, filter="songs", limit=limit)

    def search_artists(self, query: str, limit: int = 4) -> List[Dict[str, Any]]:
        if not self.client:
            from ytmusicapi import YTMusic

            unauth = YTMusic()
            return unauth.search(query=query, filter="artists", limit=limit)
        return self.client.search(query=query, filter="artists", limit=limit)

    def add_song_to_inbox(self, video_id: str) -> Tuple[str, Optional[str], bool]:
        if not self.client:
            raise RuntimeError("YouTube Music client is not authenticated")

        playlist_id = self.get_or_create_playlist(settings.inbox_playlist)
        existing_ids = self.get_inbox_video_ids(playlist_id)

        if video_id in existing_ids:
            return playlist_id, None, True

        res = self.client.add_playlist_items(playlist_id, [video_id], duplicates=False)
        set_video_id = None
        if isinstance(res, dict):
            actions = res.get("actions", [])
            for action in actions:
                set_video_id = action.get("setVideoId")
                if set_video_id:
                    break

        return playlist_id, set_video_id, False

    def add_artist_top_tracks(self, browse_id: str) -> Tuple[str, str, List[CandidateTrack]]:
        if not self.client:
            raise RuntimeError("YouTube Music client is not authenticated")

        playlist_id = self.get_or_create_playlist(settings.artists_playlist)
        artist_data = self.client.get_artist(browse_id)
        artist_name = artist_data.get("name", "Unknown Artist")
        songs_section = artist_data.get("songs", {})
        results = songs_section.get("results", [])

        # Take up to top 3 songs
        top_songs = results[:3]
        video_ids = [s.get("videoId") for s in top_songs if s.get("videoId")]

        added_tracks: List[CandidateTrack] = []
        if video_ids:
            self.client.add_playlist_items(playlist_id, video_ids, duplicates=True)
            for s in top_songs:
                vid = s.get("videoId")
                if vid:
                    added_tracks.append(
                        CandidateTrack(
                            videoId=vid,
                            title=s.get("title", "Unknown Title"),
                            artist=artist_name,
                        )
                    )

        return playlist_id, artist_name, added_tracks

    def undo_save(self, playlist_id: str, items: List[Dict[str, Any]]) -> int:
        if not self.client:
            raise RuntimeError("YouTube Music client is not authenticated")

        res = self.client.remove_playlist_items(playlist_id, items)
        if isinstance(res, str) and res == "STATUS_SUCCEEDED":
            return len(items)
        return len(items)

    def rate_song(self, video_id: str, rating: str = "LIKE") -> bool:
        if not self.client:
            raise RuntimeError("YouTube Music client is not authenticated")
        self.client.rate_song(video_id, rating)
        return True


ytm_client = YouTubeMusicClient()
