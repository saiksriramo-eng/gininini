"""Phase 0 Smoke Test: Searches for a song, ensures 'Discovery Inbox' exists, and adds the track."""

import os
import sys
from pathlib import Path

# Add backend directory to sys.path
backend_dir = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(backend_dir))

from app.config import settings
from app.resolve import clean_text


def run_smoke_test(query: str = "Seedhe Maut 101") -> None:
    print("=" * 60)
    print("  Ginininini Phase 0: YouTube Music Ingestion Smoke Test")
    print("=" * 60)

    auth_path = settings.ytm_auth_file
    if not auth_path or not os.path.exists(auth_path):
        print(f"\n[ERROR] YouTube Music auth file not found at: {auth_path}")
        print("Please follow docs/RUNBOOK.md (Section 2.2) to generate browser.json.")
        sys.exit(1)

    try:
        from ytmusicapi import YTMusic

        print(f"[1/4] Loading credentials from {auth_path}...")
        ytm = YTMusic(auth_path)
    except Exception as e:
        print(f"[ERROR] Failed to initialize ytmusicapi: {e}")
        sys.exit(1)

    cleaned = clean_text(query)
    print(f"[2/4] Searching YouTube Music for: '{cleaned}'...")
    try:
        results = ytm.search(query=cleaned, filter="songs", limit=3)
        if not results:
            print(f"[ERROR] No search results found for: '{cleaned}'")
            sys.exit(1)

        best = results[0]
        video_id = best["videoId"]
        title = best.get("title", "Unknown")
        artists = ", ".join(a.get("name", "") for a in best.get("artists", []))
        print(f"      Matched track: '{title}' by '{artists}' (ID: {video_id})")
    except Exception as e:
        print(f"[ERROR] Search failed: {e}")
        sys.exit(1)

    playlist_name = settings.inbox_playlist
    print(f"[3/4] Locating or creating playlist: '{playlist_name}'...")
    try:
        playlists = ytm.get_library_playlists(limit=100)
        playlist_id = None
        for pl in playlists:
            if pl.get("title", "").strip().lower() == playlist_name.lower():
                playlist_id = pl["playlistId"]
                print(f"      Found existing playlist ID: {playlist_id}")
                break

        if not playlist_id:
            print(f"      Creating new playlist: '{playlist_name}'...")
            playlist_id = ytm.create_playlist(
                title=playlist_name,
                description="Auto-generated by Ginininini",
                privacy_status="PRIVATE",
            )
            print(f"      Created playlist ID: {playlist_id}")
    except Exception as e:
        print(f"[ERROR] Playlist operation failed: {e}")
        sys.exit(1)

    print(f"[4/4] Adding '{title}' to '{playlist_name}'...")
    try:
        res = ytm.add_playlist_items(playlist_id, [video_id], duplicates=False)
        print("      Add response:", res)
    except Exception as e:
        print(f"[ERROR] Failed to add track to playlist: {e}")
        sys.exit(1)

    print("\n" + "=" * 60)
    print("  PHASE 0 GATE TEST READY!")
    print(f"  Song Added: '{title}' by '{artists}'")
    print(f"  Target Playlist: '{playlist_name}'")
    print("  Open YouTube Music on your moto g86 power 5G.")
    print("  Verify that the track appears in your 'Discovery Inbox'.")
    print("=" * 60)


if __name__ == "__main__":
    test_query = sys.argv[1] if len(sys.argv) > 1 else "Seedhe Maut 101"
    run_smoke_test(test_query)
